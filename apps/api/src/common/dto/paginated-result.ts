/**
 * Общая форма постраничного ответа, которую возвращают list-запросы
 * (например, `ListExpensesQuery`).
 */
export interface PaginatedResult<T> {
  /** Элементы текущей страницы. */
  items: T[];
  /** Общее количество записей, подходящих под фильтр (без учёта пагинации). */
  total: number;
  /** Номер текущей страницы, начиная с 1. */
  page: number;
  /** Размер страницы. */
  limit: number;
}
